"""Regenerate every pixel-art asset in the game.

    python3 Tools/art/build.py [fighters] [stages] [ui] [fx] [fonts] [docs]

With no arguments every game asset is rebuilt ("docs" = README images, on request only).  Run from the repo root; outputs go
to Assets/ and Scripts/Fighters/SpriteSheet.g.cs.  Requires only Pillow.
"""
import os
import sys

from PIL import Image

import anims
import font
import fx
import rig
import sheet
import stages
import ui
from fighters import FIGHTERS

A = "Assets"


def out(*parts):
    path = os.path.join(A, *parts)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return path


def build_fighters():
    import fighters
    for key in FIGHTERS:
        fighters.ALT = False
        sheet.sheet(key).save(out("Sprites", "Fighters", key + ".png"))
        fighters.ALT = True      # second-player colours for mirror matches
        sheet.sheet(key).save(out("Sprites", "Fighters", key + "_alt.png"))
        fighters.ALT = False
        print("fighter", key)
    names = anims.FRAMES
    rows = (len(names) + anims.COLS - 1) // anims.COLS
    with open("Scripts/Fighters/SpriteSheet.g.cs", "w") as f:
        f.write("// <auto-generated> by Tools/art/build.py - do not edit by hand. </auto-generated>\n")
        f.write("namespace StreepFighter;\n\n")
        f.write("/// <summary>Layout of every fighter sheet in Assets/Sprites/Fighters.</summary>\n")
        f.write("public static class SpriteSheet\n{\n")
        f.write("    public const int CellW = %d, CellH = %d;\n" % rig.CELL)
        f.write("    public const int OriginX = %d, OriginY = %d;\n" % rig.ORG)
        f.write("    public const int Columns = %d, Rows = %d;\n\n" % (anims.COLS, rows))
        for i, n in enumerate(names):
            f.write("    public const int %s = %d;\n" % (n[0].upper() + n[1:], i))
        f.write("}\n")


def build_stages():
    for key in stages.KEYS:
        try:
            far, main = stages.build(key)
        except ModuleNotFoundError:
            print("stage", key, "MISSING (no stage_%s.py yet)" % key)
            continue
        far.save(out("Stages", key + "_far.png"))
        main.save(out("Stages", key + "_main.png"))
        full = far.crop((32, 0, 32 + 384, 216)).convert("RGBA")
        full.alpha_composite(main.crop((64, 0, 448, 216)))
        thumb = full.convert("RGB").resize((96, 54), Image.BOX).quantize(48, dither=Image.NONE).convert("RGB")
        thumb.save(out("Stages", key + "_thumb.png"))
        print("stage", key)


def build_ui():
    ui.title_bg().save(out("UI", "title_bg.png"))
    ui.title_logo().save(out("UI", "logo.png"))
    ui.kombat_logo().save(out("UI", "kombat.png"))
    ui.select_bg().save(out("UI", "select_bg.png"))
    ui.ko_badge().save(out("UI", "ko_badge.png"))
    ui.round_marker(True).save(out("UI", "round_won.png"))
    ui.round_marker(False).save(out("UI", "round_empty.png"))
    ui.star(True).save(out("UI", "star_on.png"))
    ui.star(False).save(out("UI", "star_off.png"))
    for i, (key, *_rest) in enumerate(ui.PORTRAITS):
        ui.portrait(i).save(out("UI", "portrait_%s.png" % key))
        ui.portrait(i, (80, 100), 28).save(out("UI", "portrait_%s_big.png" % key))
    for name, text, scale in (("round1", "ROUND 1", 4), ("round2", "ROUND 2", 4), ("round3", "ROUND 3", 4),
                              ("final", "FINAL ROUND", 3), ("fight", "FIGHT!", 6), ("ko", "K.O.", 7),
                              ("timeover", "TIME OVER", 4), ("draw", "DRAW GAME", 4), ("perfect", "PERFECT", 4),
                              ("youwin", "YOU WIN", 4), ("youlose", "YOU LOSE", 4), ("vs", "VS", 6)):
        ui.announce(text, scale).save(out("UI", "announce_%s.png" % name))
    print("ui")


def build_docs():
    """Images for the README (not shipped with the game)."""
    import fighters
    fighters.ALT = False
    os.makedirs("docs/roster", exist_ok=True)
    names = ["MIRANDA PRIESTLY", "JULIA CHILD", "MARGARET THATCHER", "THE WITCH", "DONNA SHERIDAN",
             "SISTER ALOYSIUS"]
    for i, (key, *_rest) in enumerate(ui.PORTRAITS):
        card = ui.roster_card(i, sheet.render_frame(key, "idle0"), names[i])
        card.resize((card.width * 3, card.height * 3), Image.NEAREST).save("docs/roster/%s.png" % key)
    # each stage as framed in game (camera centred), with its home fighter celebrating
    import fx
    os.makedirs("docs/stages", exist_ok=True)
    home = dict(zip(stages.KEYS, ["miranda", "julia", "thatcher", "witch", "donna", "aloysius"]))
    for key in stages.KEYS:
        far, main = stages.build(key)
        cam = (stages.STAGE_W - stages.SCREEN_W) // 2
        shot = far.crop((cam // 2, 0, cam // 2 + stages.SCREEN_W, stages.STAGE_H)).convert("RGBA")
        shot.alpha_composite(main.crop((cam, 0, cam + stages.SCREEN_W, stages.STAGE_H)))
        x, shadow = 112, fx.shadow()
        shot.alpha_composite(shadow, (x - shadow.width // 2, stages.FLOOR_Y - 3))
        shot.alpha_composite(sheet.render_frame(home[key], "win1"), (x - rig.ORG[0], stages.FLOOR_Y - rig.ORG[1]))
        shot.convert("RGB").resize((shot.width * 2, shot.height * 2), Image.NEAREST).save("docs/stages/%s.png" % key)
    logo = ui.title_logo()
    logo = logo.crop(logo.getbbox())                   # trim the transparent margin
    logo.resize((logo.width * 2, logo.height * 2), Image.NEAREST).save("docs/logo.png")
    kombat = ui.kombat_logo()
    kombat.resize((kombat.width * 2, kombat.height * 2), Image.NEAREST).save("docs/kombat.png")
    print("docs")


def build_fx():
    for name in ("hitspark", "blockspark", "dust", "pot", "curse", "shadow"):
        getattr(fx, name)().save(out("Sprites", "FX", name + ".png"))
    print("fx")


def build_fonts():
    ink = (24, 16, 40)
    font.export_bmfont(out("Fonts", "pixel"), "StreepPixel", shadow=ink)
    font.export_bmfont(out("Fonts", "bold"), "StreepBold", bold=True, outline=ink, shadow=ink)
    font.export_bmfont(out("Fonts", "big"), "StreepBig", bold=True, scale=2, outline=ink,
                       gradient=[(252, 248, 160), (252, 216, 0), (248, 168, 0), (248, 120, 0)])
    font.export_bmfont(out("Fonts", "tiny"), "StreepTiny", tiny=True, shadow=ink)
    print("fonts")


if __name__ == "__main__":
    what = sys.argv[1:] or ["fighters", "stages", "ui", "fx", "fonts"]
    for w in what:
        globals()["build_" + w]()
